public class ArethmaticOperations {
    public static void main(String[] args) {

        double grade1=3.5;
        double grade2=5.4;
        double grade3=9.9;
        double average = (grade1+grade2+grade3)/3;
        System.out.println("The average is " + average);

        int i = 5;
        System.out.println("old i is " + i);
        i++;
        System.out.println("New i is " + i);

        int j = 7;
        System.out.println("old j is " + j);
        j--;
        System.out.println("New j is " + j);

        int k = 6;
        k+=8;
        System.out.println(k);

        int l = 5;
        l-=2;
        System.out.println(l);

        double m = 3;
        m/=8;
        System.out.println(m);

    }
}
